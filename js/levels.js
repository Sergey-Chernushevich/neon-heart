export function createLevel(index) {
  state.bricks.length   = 0;
  state.powerUps.length = 0;

  const layout     = levels[index];
  const cols       = layout[0].length;
  const brickWidth = canvas.width / cols;

  layout.forEach((row, r) => {
    row.forEach((cell, c) => {
      if (!cell) return;
      state.bricks.push({
        x:      c * brickWidth,
        y:      BRICK_TOP_OFFSET + r * BRICK_ROW_STEP,
        width:  brickWidth - BRICK_GAP,
        height: BRICK_HEIGHT,
        alive:  true,
      });
    });
  });
}
